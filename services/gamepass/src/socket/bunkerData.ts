export function makeBio(): string {
  const gender = Math.random() < 0.5 ? "Мужчина" : "Женщина";
  const age = 18 + Math.floor(Math.random() * 63);
  const fert = Math.random() < 0.15 ? "бесплоден(на)" : "может иметь детей";
  const exp = age >= 50 ? "большой жизненный опыт" : age <= 25 ? "молодость и энергия" : "расцвет сил";
  return `${gender}, ${age} лет, ${fert}, ${exp}`;
}

export function pick<T>(arr: T[], used: Set<T>): T {
  for (let i = 0; i < 50; i += 1) {
    const v = arr[Math.floor(Math.random() * arr.length)];
    if (!used.has(v)) {
      used.add(v);
      return v;
    }
  }
  return arr[Math.floor(Math.random() * arr.length)];
}
